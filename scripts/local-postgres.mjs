import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, appendFileSync, writeFileSync, accessSync, constants } from "node:fs";
import { dirname, isAbsolute, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const DEFAULT_PORT = 55432;
const DEFAULT_HOST = "127.0.0.1";
const DEFAULT_DB = "oa_commercial";
const DEFAULT_USER = "oa";
const DEFAULT_PASSWORD = "oa_dev_password";
const REQUIRED_BINARIES = Object.freeze(["pg_ctl", "initdb", "psql", "createdb"]);

function splitPath(pathValue = "") {
  return pathValue.split(":").map((item) => item.trim()).filter(Boolean);
}

function unique(values) {
  return [...new Set(values.filter(Boolean))];
}

function pathExistsExecutable(path) {
  try {
    accessSync(path, constants.X_OK);
    return true;
  } catch {
    return false;
  }
}

function commandOk(result) {
  return result.status === 0;
}

function runCommand(binary, args, options = {}) {
  const result = spawnSync(binary, args, {
    cwd: options.cwd,
    encoding: "utf8",
    env: options.env || process.env,
    stdio: options.stdio || "pipe"
  });
  if (!commandOk(result)) {
    const output = [result.stdout, result.stderr].filter(Boolean).join("\n").trim();
    throw new Error(`${binary} ${args.join(" ")} failed${output ? `: ${output}` : ""}`);
  }
  return result;
}

function safePgIdentifier(value, label) {
  const text = String(value || "").trim();
  if (!/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(text)) {
    throw new Error(`${label} must be a safe PostgreSQL identifier.`);
  }
  return text;
}

function sqlLiteral(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function dotenvLine(key, value) {
  return `${key}="${String(value).replaceAll("\\", "\\\\").replaceAll("\"", "\\\"")}"`;
}

export function buildDatabaseUrl({ database, host, password, port, user }) {
  return `postgresql://${encodeURIComponent(user)}:${encodeURIComponent(password)}@${host}:${port}/${encodeURIComponent(database)}?schema=public`;
}

export function localPostgresSearchDirs(env = process.env) {
  return unique([
    env.LOCAL_POSTGRES_BIN_DIR,
    "/opt/homebrew/opt/postgresql@16/bin",
    "/opt/homebrew/opt/postgresql@15/bin",
    "/usr/local/opt/postgresql@16/bin",
    "/usr/local/opt/postgresql@15/bin",
    ...splitPath(env.PATH)
  ]);
}

export function resolvePostgresBinaries(env = process.env) {
  const searchDirs = localPostgresSearchDirs(env);
  const binaries = {};
  const missing = [];

  REQUIRED_BINARIES.forEach((name) => {
    const match = searchDirs.map((dir) => join(dir, name)).find(pathExistsExecutable);
    if (match) {
      binaries[name] = match;
    } else {
      missing.push(name);
    }
  });

  return { binaries, missing, searchDirs };
}

export function buildLocalPostgresConfig(env = process.env, rootDir = process.cwd()) {
  const dataRoot = env.LOCAL_POSTGRES_DIR
    ? (isAbsolute(env.LOCAL_POSTGRES_DIR) ? env.LOCAL_POSTGRES_DIR : resolve(rootDir, env.LOCAL_POSTGRES_DIR))
    : resolve(rootDir, ".local-postgres");
  const database = safePgIdentifier(env.LOCAL_POSTGRES_DB || env.POSTGRES_DB || DEFAULT_DB, "LOCAL_POSTGRES_DB");
  const user = safePgIdentifier(env.LOCAL_POSTGRES_USER || env.POSTGRES_USER || DEFAULT_USER, "LOCAL_POSTGRES_USER");
  const password = env.LOCAL_POSTGRES_PASSWORD || env.POSTGRES_PASSWORD || DEFAULT_PASSWORD;
  const host = env.LOCAL_POSTGRES_HOST || DEFAULT_HOST;
  const port = Number.parseInt(env.LOCAL_POSTGRES_PORT || env.POSTGRES_PORT || `${DEFAULT_PORT}`, 10);
  if (!Number.isInteger(port) || port <= 0 || port > 65535) {
    throw new Error("LOCAL_POSTGRES_PORT must be a valid TCP port.");
  }

  return {
    dataDir: resolve(dataRoot, "data"),
    dataRoot,
    database,
    dotenvPath: resolve(dataRoot, ".env.local-postgres"),
    host,
    logPath: resolve(dataRoot, "postgres.log"),
    password,
    port,
    rootDir,
    user
  };
}

export function renderLocalPostgresEnv(config) {
  const databaseUrl = buildDatabaseUrl(config);
  return [
    "# Generated by npm run postgres:local -- write-env",
    "# Local development only. Do not use these values for production.",
    dotenvLine("DATABASE_URL", databaseUrl),
    dotenvLine("POSTGRES_HOST", config.host),
    dotenvLine("POSTGRES_PORT", config.port),
    dotenvLine("POSTGRES_DB", config.database),
    dotenvLine("POSTGRES_USER", config.user),
    dotenvLine("POSTGRES_PASSWORD", config.password),
    dotenvLine("SERVER_HOST", "127.0.0.1"),
    dotenvLine("SERVER_PORT", "8787"),
    dotenvLine("API_BASE_URL", "http://127.0.0.1:8787"),
    dotenvLine("VITE_REQUIRE_API", "1"),
    dotenvLine("VITE_DEMO_FALLBACK", "0"),
    ""
  ].join("\n");
}

export function buildCheckReport({ config, resolved }) {
  const ok = resolved.missing.length === 0;
  return {
    ok,
    action: "check",
    dataDir: config.dataDir,
    databaseUrl: buildDatabaseUrl(config).replace(config.password, "********"),
    dotenvPath: config.dotenvPath,
    missingBinaries: resolved.missing,
    nextSteps: ok
      ? [
          "Run npm run postgres:local -- start to start the project-local PostgreSQL cluster.",
          "Run npm run db:deploy && npm run db:seed, then npm run dev:commercial."
        ]
      : [
          "Install PostgreSQL 16 locally, for example: brew install postgresql@16.",
          "If PostgreSQL is installed outside PATH, set LOCAL_POSTGRES_BIN_DIR=/path/to/postgresql/bin.",
          "Rerun npm run postgres:local -- check --json."
        ],
    port: config.port,
    searchDirs: resolved.searchDirs,
    user: config.user
  };
}

function ensureClusterInitialized(config, binaries) {
  mkdirSync(config.dataRoot, { recursive: true, mode: 0o700 });
  if (existsSync(join(config.dataDir, "PG_VERSION"))) return;
  runCommand(binaries.initdb, [
    "-D", config.dataDir,
    "-U", config.user,
    "--encoding=UTF8",
    "--auth=trust"
  ]);
  appendFileSync(
    join(config.dataDir, "postgresql.conf"),
    [
      "",
      "# Project-local OA development overrides",
      `listen_addresses = '${config.host}'`,
      `port = ${config.port}`,
      ""
    ].join("\n")
  );
}

function pgEnv(config) {
  return {
    ...process.env,
    PGDATABASE: "postgres",
    PGHOST: config.host,
    PGPASSWORD: config.password,
    PGPORT: String(config.port),
    PGUSER: config.user
  };
}

function ensureDatabase(config, binaries) {
  const env = pgEnv(config);
  runCommand(binaries.psql, [
    "-d", "postgres",
    "-v", "ON_ERROR_STOP=1",
    "-c", `ALTER USER ${config.user} WITH PASSWORD ${sqlLiteral(config.password)};`
  ], { env });
  const exists = spawnSync(binaries.psql, [
    "-d", "postgres",
    "-tAc", `SELECT 1 FROM pg_database WHERE datname = ${sqlLiteral(config.database)};`
  ], { encoding: "utf8", env });
  if (!commandOk(exists)) {
    const output = [exists.stdout, exists.stderr].filter(Boolean).join("\n").trim();
    throw new Error(`database existence check failed${output ? `: ${output}` : ""}`);
  }
  if (exists.stdout.trim() === "1") return;
  runCommand(binaries.createdb, ["-h", config.host, "-p", String(config.port), "-U", config.user, config.database], { env });
}

function writeDotenv(config) {
  mkdirSync(dirname(config.dotenvPath), { recursive: true, mode: 0o700 });
  writeFileSync(config.dotenvPath, renderLocalPostgresEnv(config), { mode: 0o600 });
}

function pgCtl(config, binaries, args, options = {}) {
  return runCommand(binaries.pg_ctl, ["-D", config.dataDir, ...args], options);
}

function clusterIsRunning(config, binaries) {
  if (!existsSync(join(config.dataDir, "PG_VERSION"))) return false;
  const status = spawnSync(binaries.pg_ctl, ["-D", config.dataDir, "status"], { encoding: "utf8" });
  return status.status === 0;
}

function startCluster(config, binaries) {
  ensureClusterInitialized(config, binaries);
  if (!clusterIsRunning(config, binaries)) {
    pgCtl(config, binaries, [
      "-l", config.logPath,
      "-o", `-p ${config.port} -c listen_addresses=${config.host}`,
      "start",
      "-w",
      "-t", "20"
    ]);
  }
  ensureDatabase(config, binaries);
  writeDotenv(config);
  return {
    ok: true,
    action: "start",
    dataDir: config.dataDir,
    database: config.database,
    dotenvPath: config.dotenvPath,
    host: config.host,
    logPath: config.logPath,
    nextSteps: [
      `DATABASE_URL="${buildDatabaseUrl(config)}" npm run db:deploy`,
      `DATABASE_URL="${buildDatabaseUrl(config)}" RUN_DB_SEED=1 npm run db:seed`,
      `DATABASE_URL="${buildDatabaseUrl(config)}" npm run dev:commercial`
    ],
    port: config.port
  };
}

function stopCluster(config, binaries) {
  if (!existsSync(join(config.dataDir, "PG_VERSION"))) {
    return { ok: true, action: "stop", message: "Local PostgreSQL cluster is not initialized.", dataDir: config.dataDir };
  }
  pgCtl(config, binaries, ["stop", "-m", "fast"], { stdio: "pipe" });
  return { ok: true, action: "stop", dataDir: config.dataDir };
}

function statusCluster(config, binaries) {
  if (!existsSync(join(config.dataDir, "PG_VERSION"))) {
    return { ok: false, action: "status", message: "Local PostgreSQL cluster is not initialized.", dataDir: config.dataDir };
  }
  const status = spawnSync(binaries.pg_ctl, ["-D", config.dataDir, "status"], { encoding: "utf8" });
  return {
    ok: status.status === 0,
    action: "status",
    dataDir: config.dataDir,
    output: [status.stdout, status.stderr].filter(Boolean).join("\n").trim()
  };
}

export function parseLocalPostgresArgs(argv = []) {
  const args = [...argv];
  const action = args.find((item) => !item.startsWith("-")) || "check";
  return {
    action,
    json: args.includes("--json")
  };
}

function printReport(report, jsonMode) {
  if (jsonMode) {
    console.log(JSON.stringify(report, null, 2));
    return;
  }
  console.log(`${report.ok ? "OK" : "NOT READY"}: local PostgreSQL ${report.action}`);
  if (report.message) console.log(report.message);
  if (report.missingBinaries?.length) console.log(`Missing binaries: ${report.missingBinaries.join(", ")}`);
  if (report.dotenvPath) console.log(`Env file: ${report.dotenvPath}`);
  if (report.dataDir) console.log(`Data dir: ${report.dataDir}`);
  if (report.nextSteps?.length) {
    console.log("Next steps:");
    report.nextSteps.forEach((step) => console.log(`- ${step}`));
  }
}

export function runLocalPostgresCli(argv = process.argv.slice(2), env = process.env, rootDir = process.cwd()) {
  const { action, json } = parseLocalPostgresArgs(argv);
  const config = buildLocalPostgresConfig(env, rootDir);
  const resolved = resolvePostgresBinaries(env);
  if (action === "check") {
    const report = buildCheckReport({ config, resolved });
    printReport(report, json);
    return report.ok ? 0 : 66;
  }
  if (action === "write-env") {
    writeDotenv(config);
    const report = { ok: true, action, dotenvPath: config.dotenvPath, databaseUrl: buildDatabaseUrl(config).replace(config.password, "********") };
    printReport(report, json);
    return 0;
  }
  if (resolved.missing.length) {
    const report = { ...buildCheckReport({ config, resolved }), action, ok: false };
    printReport(report, json);
    return 66;
  }
  const actions = {
    start: () => startCluster(config, resolved.binaries),
    status: () => statusCluster(config, resolved.binaries),
    stop: () => stopCluster(config, resolved.binaries)
  };
  if (!actions[action]) {
    throw new Error(`Unknown local PostgreSQL action: ${action}. Use check, write-env, start, stop, or status.`);
  }
  const report = actions[action]();
  printReport(report, json);
  return report.ok ? 0 : 1;
}

