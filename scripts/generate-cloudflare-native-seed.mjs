import { writeFileSync } from "node:fs";
import { loadDashboardPeople } from "./dashboard-data.mjs";

function maskText(value) {
  const text = String(value || "").trim();
  return text ? `${text.slice(0, 2)}***` : "";
}

function sanitizePerson(person) {
  return {
    ...person,
    hukou: maskText(person.hukou),
    major: maskText(person.major),
    school: maskText(person.school)
  };
}

function buildNativeSeed() {
  const people = loadDashboardPeople();
  return {
    source: "oa-dashboard.html",
    counts: {
      employees: people.employees.length,
      femaleEmployees: people.femaleEmployees.length,
      leavers: people.leavers.length,
      monthLeavers: people.monthLeavers.length
    },
    people: {
      ...people,
      employees: people.employees.map(sanitizePerson),
      femaleEmployees: people.femaleEmployees.map(sanitizePerson),
      leavers: people.leavers.map(sanitizePerson),
      monthLeavers: people.monthLeavers.map(sanitizePerson)
    }
  };
}

const outputPath = new URL("../cloudflare/native-seed-data.js", import.meta.url);
const source = `// Generated by scripts/generate-cloudflare-native-seed.mjs from oa-dashboard.html.
// Personnel-sensitive fields are masked before being embedded in the Worker bundle.
export const nativeSeedData = ${JSON.stringify(buildNativeSeed(), null, 2)};
`;

writeFileSync(outputPath, source);
console.log(`Wrote ${outputPath.pathname}`);
